-- S15P31A108-400. Generated suggestions are separate from immutable plan revisions.
create table task_plan_revision_proposal (
    id bigint generated by default as identity primary key,
    project_id bigint not null references project(id),
    task_id bigint not null references task(id),
    created_by_account_id bigint not null references account(id),
    baseline_id bigint not null,
    plan_revision_id bigint not null references task_plan_revision(id),
    expected_revision_no integer not null,
    expected_lock_version integer not null,
    source_validation_id bigint not null references validation(id),
    source_validation_lock_version integer not null,
    content jsonb not null,
    expires_at timestamptz not null,
    applied_validation_id bigint references validation(id),
    applied_at timestamptz,
    created_at timestamptz not null default now()
);
create index idx_task_plan_proposal_task on task_plan_revision_proposal(task_id, id desc);
